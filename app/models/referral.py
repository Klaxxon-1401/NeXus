"""Referral tree edges and commission records."""

from __future__ import annotations

import uuid
from typing import TYPE_CHECKING

from sqlalchemy import (
    BigInteger,
    CheckConstraint,
    ForeignKey,
    Index,
    Integer,
    String,
    UniqueConstraint,
    Uuid,
)
from sqlalchemy.orm import Mapped, mapped_column, relationship

from .base import Base, TimestampMixin, UUIDPrimaryKeyMixin

if TYPE_CHECKING:  # pragma: no cover
    from .investment import Investment
    from .transaction import Transaction
    from .user import User


class Referral(UUIDPrimaryKeyMixin, TimestampMixin, Base):
    """One direct edge in a workspace's referral graph.

    ``referrer`` invited ``referred_user``. Indirect relationships are derived
    by walking these edges upward, which keeps the graph normalised and makes
    the five-level cap an engine policy rather than a schema limitation.
    """

    __tablename__ = "referrals"
    __table_args__ = (
        CheckConstraint("status IN ('active', 'inactive')", name="referral_status"),
        UniqueConstraint("referred_user_id", name="uq_referral_referred_user"),
        Index("ix_referrals_tenant_referrer", "tenant_id", "referrer_id"),
        CheckConstraint("referrer_id <> referred_user_id", name="referral_not_self"),
    )

    tenant_id: Mapped[uuid.UUID] = mapped_column(
        Uuid(as_uuid=True),
        ForeignKey("tenants.id", ondelete="RESTRICT"),
        nullable=False,
        index=True,
    )
    referrer_id: Mapped[uuid.UUID] = mapped_column(
        Uuid(as_uuid=True),
        ForeignKey("users.id", ondelete="RESTRICT"),
        nullable=False,
        index=True,
    )
    referred_user_id: Mapped[uuid.UUID] = mapped_column(
        Uuid(as_uuid=True),
        ForeignKey("users.id", ondelete="RESTRICT"),
        nullable=False,
        unique=True,
    )
    code_used: Mapped[str] = mapped_column(String(16), nullable=False)
    status: Mapped[str] = mapped_column(String(20), default="active", nullable=False)

    referrer: Mapped["User"] = relationship(foreign_keys=[referrer_id])
    referred_user: Mapped["User"] = relationship(foreign_keys=[referred_user_id])


class ReferralCommission(UUIDPrimaryKeyMixin, TimestampMixin, Base):
    """Immutable record of a referral payout generated by an investment.

    The unique constraint is the second line of defence against double-paying
    a commission during retries or concurrent settlement jobs.
    """

    __tablename__ = "referral_commissions"
    __table_args__ = (
        CheckConstraint("level >= 1 AND level <= 5", name="commission_level_range"),
        CheckConstraint("rate_bps >= 0 AND rate_bps <= 10000", name="commission_rate_range"),
        CheckConstraint("amount_cents >= 0", name="commission_amount_nonnegative"),
        UniqueConstraint("investment_id", "beneficiary_id", name="uq_commission_investment_beneficiary"),
        Index("ix_commissions_tenant_beneficiary", "tenant_id", "beneficiary_id"),
        Index("ix_commissions_tenant_source", "tenant_id", "source_user_id"),
    )

    tenant_id: Mapped[uuid.UUID] = mapped_column(
        Uuid(as_uuid=True),
        ForeignKey("tenants.id", ondelete="RESTRICT"),
        nullable=False,
        index=True,
    )
    beneficiary_id: Mapped[uuid.UUID] = mapped_column(
        Uuid(as_uuid=True),
        ForeignKey("users.id", ondelete="RESTRICT"),
        nullable=False,
    )
    source_user_id: Mapped[uuid.UUID] = mapped_column(
        Uuid(as_uuid=True),
        ForeignKey("users.id", ondelete="RESTRICT"),
        nullable=False,
    )
    investment_id: Mapped[uuid.UUID] = mapped_column(
        Uuid(as_uuid=True),
        ForeignKey("investments.id", ondelete="CASCADE"),
        nullable=False,
    )
    transaction_id: Mapped[uuid.UUID] = mapped_column(
        Uuid(as_uuid=True),
        ForeignKey("transactions.id", ondelete="RESTRICT"),
        nullable=False,
        unique=True,
    )
    level: Mapped[int] = mapped_column(Integer, nullable=False)
    rate_bps: Mapped[int] = mapped_column(Integer, nullable=False)
    amount_cents: Mapped[int] = mapped_column(BigInteger, nullable=False)

    beneficiary: Mapped["User"] = relationship(foreign_keys=[beneficiary_id])
    source_user: Mapped["User"] = relationship(foreign_keys=[source_user_id])
    investment: Mapped["Investment"] = relationship()
    transaction: Mapped["Transaction"] = relationship()
